def load_excel_data():
    print(f"Loading data from {EXCEL_PATH}...")
    df = pd.read_excel(EXCEL_PATH)
    print(f"  Loaded {len(df)} rows")
    return df


def filter_ohio_hospitals(df):
    ohio_df = df[df['State'] == 'OH'].copy()
    print(f"  Filtered to {len(ohio_df)} Ohio rows")
    return ohio_df


def pivot_hospital_data(df):
    hospital_info_cols = ['Facility ID', 'Facility Name', 'Address', 'City/Town', 
                          'State', 'ZIP Code', 'County/Parish', 'Telephone Number']
    
    hospital_info = df[hospital_info_cols].drop_duplicates(subset=['Facility ID'])
    
    measures_pivot = df.pivot_table(
        index='Facility ID',
        columns='Measure ID',
        values='Score',
        aggfunc='first'
    ).reset_index()
    
    result = hospital_info.merge(measures_pivot, on='Facility ID', how='left')
    print(f"  Pivoted to {len(result)} unique hospitals")
    return result


def add_coordinates(df):
    print("Adding coordinates from ZIP code lookup...")
    df = df.copy()
    df['geo_lat'] = None
    df['geo_lng'] = None
    
    geocoded = 0
    for idx, row in df.iterrows():
        zip_code = str(row.get('ZIP Code', '')).strip()
        if len(zip_code) >= 5:
            zip_prefix = zip_code[:5]
            coords = OHIO_ZIP_COORDS.get(zip_prefix)
            if coords:
                df.at[idx, 'geo_lat'] = coords[0]
                df.at[idx, 'geo_lng'] = coords[1]
                geocoded += 1
    
    print(f"  Added coordinates for {geocoded} of {len(df)} hospitals")
    return df


def create_database(df):
    print(f"Creating database at {DB_PATH}...")
    
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    
    cursor.execute("DROP TABLE IF EXISTS maternity_hospitals")
    
    cursor.execute("""
        CREATE TABLE maternity_hospitals (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            facility_id TEXT UNIQUE,
            facility_name TEXT,
            address TEXT,
            city TEXT,
            state TEXT,
            zip_code TEXT,
            county TEXT,
            phone TEXT,
            geo_lat REAL,
            geo_lng REAL,
            cesarean_rate TEXT,
            smm_rate TEXT,
            smm_rate_excl_transfusion TEXT,
            is_birthing_friendly INTEGER DEFAULT 0,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)
    
    for _, row in df.iterrows():
        cursor.execute("""
            INSERT OR REPLACE INTO maternity_hospitals 
            (facility_id, facility_name, address, city, state, zip_code, county, phone,
             geo_lat, geo_lng, cesarean_rate, smm_rate, smm_rate_excl_transfusion, is_birthing_friendly)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            str(row.get('Facility ID', '')),
            str(row.get('Facility Name', '')),
            str(row.get('Address', '')),
            str(row.get('City/Town', '')),
            str(row.get('State', 'OH')),
            str(row.get('ZIP Code', '')),
            str(row.get('County/Parish', '')),
            str(row.get('Telephone Number', '')),
            row.get('geo_lat'),
            row.get('geo_lng'),
            str(row.get('PC_02', 'Not Available')),
            str(row.get('PC_07a', 'Not Available')),
            str(row.get('PC_07b', 'Not Available')),
            0
        ))
    
    conn.commit()
    
    cursor.execute("SELECT COUNT(*) FROM maternity_hospitals")
    count = cursor.fetchone()[0]
    print(f"  Inserted {count} hospitals into database")
    
    conn.close()


